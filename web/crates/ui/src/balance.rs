//! 밸런스: 끝없이 자라는 회사. 연구실 숫자는 올라갈수록 같은 일을 해도 덜 올라요(체감).
//! "종결"은 아래 한도(서버 규칙의 한도와 같아요)에 닿는 때예요. 직원 10명이 하루 한 시간쯤 꾸준히 일하면 약 2년, 직원이 적거나 덜 일하면 훨씬 오래 걸려요.
//!
//! 계산(한 일의 평균 올림 b, 종결 값 C, 일 횟수 N): 올림이 1 ÷ (1 + 지금값 ÷ S) 배로 줄면 N번 뒤의 값 x는 x + x² ÷ 2S = b × N 이에요.
//! 종결(x = C)까지 필요한 일 횟수는 N = (C + C² ÷ 2S) ÷ b 이고, S는 직원 10명 × 730일 × 하루 한 시간 일하는 횟수로 맞췄어요.

/// 연구실 숫자 순서: 핵연료 성능, 용량, 속도, 전기값, 데이터, 식품 성능 (work.rs의 LAB_KEYS와 같아요)
pub const END: [f64; 6] = [1_000_000.0, 1_000_000.0, 1_000_000.0, 1_000_000.0, 1_000_000_000.0, 30_000_000.0];
/// 체감 정도 S (식품 성능은 서버가 에너지로 막아서 0이에요)
pub const SOFT: [f64; 6] = [12_000.0, 32_500.0, 32_500.0, 32_500.0, 830_000_000.0, 0.0];

/// 한 번에 올라가는 양에 체감을 곱하고, 소수는 확률로 올려요 (평균은 그대로예요)
pub fn eased(k: usize, cur: f64, base: f64) -> f64 {
    if k >= 6 || SOFT[k] <= 0.0 {
        return base;
    }
    let room = (END[k] - cur).max(0.0);
    let e = base / (1.0 + cur / SOFT[k]);
    let f = e.floor();
    let up = if js_sys::Math::random() < e - f { f + 1.0 } else { f };
    up.min(room)
}

/// 회사가 얼마나 자랐는지 0~1 (종류마다 보는 숫자가 달라요)
pub fn progress(kind: &str, lab: &[f64; 6]) -> f64 {
    let r = |k: usize| (lab[k] / END[k]).clamp(0.0, 1.0);
    match kind {
        "nuclear" => r(0),
        "pc" => (r(1) + r(2) + r(3)) / 3.0,
        "ai" => r(4),
        _ => r(5),
    }
}
