  const names = await p.evaluate(() => [...document.querySelectorAll('#sh-row .sh-card')].map((c) => c.querySelector('b').textContent + '|' + c.querySelector('small').textContent + '|' + c.querySelector('.sh-foot span').textContent));
  ok('순위대로 이름·순위·값', names.join(' / ') === ['에르메스 버킨|명품 1위|1,000 멸공', '구찌 GG 호보백|명품 3위|720 멸공', '샤넬 클래식 플랩|명품 4위|610 멸공', '프라다 리나일론 숄더백|명품 5위|520 멸공', '디올 오블리크 파우치|명품 6위|440 멸공', '버버리 체크 캐시미어 머플러|명품 7위|380 멸공', '펜디 FF 토트백|명품 8위|320 멸공'].join(' / '));
  ok('사진 7장이 모두 떠요', await p.evaluate(async () => { const im = [...document.querySelectorAll('#sh-row .sh-img')]; await Promise.all(im.map((i) => i.decode().catch(() => {}))); return im.length === 7 && im.every((i) => i.naturalWidth > 100); }));
  await p.click('.sh-cat[data-cat="neck"]'); await p.waitForTimeout(400);
