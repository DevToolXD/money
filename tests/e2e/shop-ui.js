// 화면: 손님이 상점에서 개수를 올리고 사요. 지갑이 줄고, 재고가 줄고, 알림이 떠요
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const emu = fs.readFileSync(path.join(__dirname, '..', 'out', 'firebase.emu.js'), 'utf8');
const res = []; const ok = (n, v) => { res.push(!!v); console.log((v ? 'PASS ' : 'FAIL ') + n); };
const DB = 'http://127.0.0.1:8081/v1/projects/money-sim-36ed8/databases/(default)/documents';
const H = { 'content-type': 'application/json', authorization: 'Bearer owner' };
const open = async (b) => {
  const page = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
  const errs = []; page.on('pageerror', (e) => errs.push(e.message));
  await page.route('**/app/firebase.js*', (r) => r.fulfill({ contentType: 'text/javascript', body: emu }));
  await page.route('**/index.html*', async (r) => { const resp = await r.fetch(); const t = (await resp.text()).replace("connect-src 'self'", "connect-src 'self' http://127.0.0.1:*"); r.fulfill({ response: resp, body: t }); });
  await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForTimeout(3500);
  return { page, errs };
};
const num = (f) => Number(f.integerValue ?? f.doubleValue);
const wallet = async (uid) => num((await (await fetch(`${DB}/wallets/${uid}`, { headers: H })).json()).fields.bal);
const setBal = (uid, bal) => fetch(`${DB}/wallets/${uid}?updateMask.fieldPaths=bal`, { method: 'PATCH', headers: H, body: JSON.stringify({ fields: { bal: { integerValue: String(bal) } } }) });
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--disable-web-security'] });
  const O = await open(b), B = await open(b);
  const sfx = Date.now().toString(36).slice(-4);
  await O.page.evaluate((u) => window.cloud.signUp(u, 'abc123', '가게주인'), 'so' + sfx);
  await O.page.reload(); await O.page.waitForTimeout(6000);
  const uO = await O.page.evaluate(() => window.cloud.uid);
  await setBal(uO, 1000); await O.page.waitForTimeout(2300);
  const cid = await O.page.evaluate(() => window.cloud.foundCompany('상점 시험', '', 'food'));
  await O.page.waitForTimeout(2300);
  await O.page.evaluate((c) => window.cloud.labCash(c, 100, 1), cid); await O.page.waitForTimeout(500);
  const pid = await O.page.evaluate((c) => window.cloud.createProduct(c, { cat: 'food', group: 'water', item: 'water', name: '시험 생수', shape: 1, cap: 3, capColor: 5, color: -1, costCents: 50, priceCents: 150, paused: false, active: true }), cid);
  await fetch(`${DB}/companies/${cid}/products/${pid}?updateMask.fieldPaths=stock`, { method: 'PATCH', headers: H, body: JSON.stringify({ fields: { stock: { integerValue: '5' } } }) });
  await B.page.evaluate((u) => window.cloud.signUp(u, 'abc123', '손님'), 'sb' + sfx);
  await B.page.reload(); await B.page.waitForTimeout(6000);
  const uB = await B.page.evaluate(() => window.cloud.uid);
  await setBal(uB, 100); await B.page.waitForTimeout(2300);
  await B.page.evaluate(() => document.querySelector('.tabbar .tab[data-tab="shop"]').click()); await B.page.waitForTimeout(2500);
  const card = (await B.page.textContent('#shop-root')) || '';
  ok('상품 카드: 이름, 가격, 재고가 보여요', card.includes('시험 생수') && card.includes('1개 1.5 토큰') && card.includes('재고 5개'));
  ok('개수 버튼 두 개가 있어요', (await B.page.$$('.shop-card .shop-round')).length === 2);
  ok('처음에는 줄이기 버튼이 꺼져 있어요', await B.page.isDisabled('.shop-card [data-d="-1"]'));
  await B.page.click('.shop-card [data-d="1"]'); await B.page.waitForTimeout(200);
  ok('늘리면 2개, 3 토큰에 사기', (await B.page.textContent('.shop-n')).trim() === '2' && (await B.page.textContent('.shop-buy')).includes('3 토큰에 사기'));
  await B.page.click('.shop-buy'); await B.page.waitForTimeout(4000);
  ok('산 뒤 알림', ((await B.page.textContent('.toast').catch(() => '')) || '').includes('시험 생수 2개를 샀어요'));
  ok('지갑 100 → 97', (await wallet(uB)) === 97);
  ok('목록이 다시 읽혀서 재고 3개', (await B.page.textContent('#shop-root')).includes('재고 3개'));
  const errs = [...O.errs, ...B.errs];
  ok('화면 오류 없음', errs.length === 0); if (errs.length) console.log(errs.slice(0, 3));
  console.log(`\n${res.filter(Boolean).length}/${res.length} 통과`);
  await b.close(); process.exit(res.every(Boolean) ? 0 : 1);
})();
