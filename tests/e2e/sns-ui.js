// 화면: SNS에서 + 버튼(SNS에서만, 계정 알약 위)으로 글을 올리고, 다른 사람이 좋아요·댓글을 달면 카드에 보여요
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const emu = fs.readFileSync(path.join(__dirname, '..', 'out', 'firebase.emu.js'), 'utf8');
const res = []; const ok = (n, v) => { res.push(!!v); console.log((v ? 'PASS ' : 'FAIL ') + n); };
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--disable-web-security'] });
  const mk = async () => {
    const page = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
    page.errs = []; page.on('pageerror', (e) => page.errs.push(e.message));
    await page.route('**/app/firebase.js*', (r) => r.fulfill({ contentType: 'text/javascript', body: emu }));
    await page.route('**/index.html*', async (r) => { const resp = await r.fetch(); const t = (await resp.text()).replace("connect-src 'self'", "connect-src 'self' http://127.0.0.1:*"); r.fulfill({ response: resp, body: t }); });
    await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForTimeout(3500);
    return page;
  };
  const go = async (p) => { await p.evaluate(() => window.tabbar.flipPage()); await p.waitForTimeout(600); await p.evaluate(() => document.querySelector('.tabbar .tab[data-tab="untitled3"]').click()); await p.waitForTimeout(3000); };
  const t = Date.now().toString(36).slice(-4);
  const a = await mk();
  await a.evaluate((u) => window.cloud.signUp(u, 'abc123', '글쓴이'), 'sna' + t);
  await a.reload(); await a.waitForTimeout(6000);
  ok('다른 탭에서는 + 버튼이 안 보여요', !(await a.isVisible('#sns-fab')));
  await go(a);
  ok('SNS에서는 + 버튼', await a.isVisible('#sns-fab'));
  const fb = await a.$eval('#sns-fab', (e) => e.getBoundingClientRect().toJSON()); const acc = await a.$eval('.tab-account', (e) => e.getBoundingClientRect().toJSON());
  ok('계정 알약 바로 위', fb.bottom <= acc.top + 2 && Math.abs((fb.left + fb.right) / 2 - (acc.left + acc.right) / 2) < 14);
  await a.click('#sns-fab'); await a.waitForTimeout(600);
  ok('새 게시물 판', await a.isVisible('#sns-compose .sns-panel'));
  await a.fill('#sns-text', '오늘 첫 매출 나왔어요');
  await a.fill('#sns-place', '성수동');
  await a.click('#sns-post'); await a.waitForTimeout(2500);
  ok('올리면 판이 닫혀요', !(await a.isVisible('#sns-compose .sns-panel')));
  ok('피드에 글', (await a.textContent('#sns-feed')).includes('오늘 첫 매출'));
  ok('장소 칩', (await a.textContent('#sns-feed .sns-chip')).includes('성수동'));
  const p = await mk();
  await p.evaluate((u) => window.cloud.signUp(u, 'abc123', '구경꾼'), 'snb' + t);
  await p.reload(); await p.waitForTimeout(6000);
  await go(p);
  ok('다른 사람도 글을 봐요', (await p.textContent('#sns-feed')).includes('오늘 첫 매출'));
  await p.click('.sns-card .sns-like'); await p.waitForTimeout(1500);
  ok('좋아요', (await p.textContent('.sns-card .sns-like')).includes('1') && await p.$eval('.sns-card .sns-like', (e) => e.classList.contains('on')));
  await p.fill('.sns-card .sns-ci', '대박이에요'); await p.press('.sns-card .sns-ci', 'Enter'); await p.waitForTimeout(2500);
  ok('댓글 수 1', (await p.textContent('.sns-card [data-act="replies"]')).includes('1'));
  await a.waitForTimeout(2500);
  ok('글쓴이 카드에 댓글 미리보기', (await a.textContent('#sns-feed')).includes('대박이에요'));
  ok('글쓴이도 좋아요 1', (await a.textContent('.sns-card .sns-like')).includes('1'));
  await p.click('.sns-card [data-act="replies"]'); await p.waitForTimeout(1500);
  ok('댓글 모두 보기', (await p.textContent('#sns-rl')).includes('대박이에요'));
  await p.click('#sns-replies [data-close]'); await p.waitForTimeout(500);
  await a.screenshot({ path: path.join(__dirname, 'shots', 'sns.png') });
  ok('화면 오류 없음', a.errs.length + p.errs.length === 0); if (a.errs.length + p.errs.length) console.log(a.errs.concat(p.errs).slice(0, 3));
  console.log(`\n${res.filter(Boolean).length}/${res.length} 통과`);
  await b.close(); process.exit(res.every(Boolean) ? 0 : 1);
})();
