// 화면: 사장이 일 탭에서 공장을 돌리고, 진행 글과 공장 추가 버튼을 확인해요
const { chromium } = require('playwright');
const fs = require('fs');
const emu = fs.readFileSync(require('path').join(__dirname, '..', 'out', 'firebase.emu.js'), 'utf8');
const res = []; const ok = (n, v) => { res.push(!!v); console.log((v ? 'PASS ' : 'FAIL ') + n); };
const DB = 'http://127.0.0.1:8081/v1/projects/money-sim-36ed8/databases/(default)/documents';
const setWallet = (uid, bal) => fetch(`${DB}/wallets/${uid}?updateMask.fieldPaths=bal`, { method: 'PATCH', headers: { 'content-type': 'application/json', authorization: 'Bearer owner' }, body: JSON.stringify({ fields: { bal: { integerValue: String(bal) } } }) });
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-web-security'] });
  const page = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
  const errs = []; page.on('pageerror', (e) => errs.push(e.message));
  await page.route('**/app/firebase.js*', (r) => r.fulfill({ contentType: 'text/javascript', body: fs.readFileSync(require('path').join(__dirname, '..', 'out', 'firebase.emu.js'), 'utf8') }));
  await page.route('**/index.html*', async (r) => { const resp = await r.fetch(); const t = (await resp.text()).replace("connect-src 'self'", "connect-src 'self' http://127.0.0.1:*"); r.fulfill({ response: resp, body: t }); });
  await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForTimeout(3500);
  const id = 'facui' + Date.now().toString(36).slice(-4);
  await page.evaluate((u) => window.cloud.signUp(u, 'abc123', '공장장'), id);
  await page.reload(); await page.waitForTimeout(6000);
  const uid = await page.evaluate(() => window.cloud.uid);
  await setWallet(uid, 1000); await page.waitForTimeout(2300);
  const cid = await page.evaluate(() => window.cloud.foundCompany('화면 공장', '', 'food'));
  await page.waitForTimeout(2300);
  await page.evaluate((c) => window.cloud.labCash(c, 600, 1), cid); await page.waitForTimeout(2300);
  const pid = await page.evaluate((c) => window.cloud.createProduct(c, { cat: 'food', group: 'water', item: 'water', name: '화면 생수', shape: 1, cap: 3, capColor: 5, color: -1, costCents: 100, priceCents: 300, paused: false, active: true }), cid);
  await page.reload(); await page.waitForTimeout(5000);
  await page.evaluate(() => document.querySelector('.tabbar .tab[data-tab="work"]').click());
  await page.waitForTimeout(2000);
  const card = await page.textContent('#screen-work');
  ok('일 탭: 공장 추가 버튼이 보여요', card.includes('공장 추가 · 500 토큰'));
  ok('일 탭: 재고 0개, 공장 1대', card.includes('공장') && (await page.textContent('#fac-count')).trim() === '1');
  await page.screenshot({ path: require('path').join(__dirname, 'shots', 'fac-card-1.png'), fullPage: false });
  await page.fill('#fac-n', '2');
  await page.waitForTimeout(300);
  ok('예상 문구: 2개 · 약 2분 · 재료값 2 토큰', (await page.textContent('#fac-est')).includes('2분'));
  await page.click('#fac-start');
  await page.waitForTimeout(2500);
  ok('돌리면 진행 글이 나와요', (await page.textContent('#fac-left')).includes('남은 2개'));
  ok('돌리는 중에는 돌리기 버튼이 꺼져요', await page.isDisabled('#fac-start'));
  await page.screenshot({ path: require('path').join(__dirname, 'shots', 'fac-card-2.png'), fullPage: false });
  ok('화면 오류 없음', errs.length === 0); if (errs.length) console.log(errs.slice(0, 3));
  console.log(`\n${res.filter(Boolean).length}/${res.length} 통과`);
  await b.close(); process.exit(res.every(Boolean) ? 0 : 1);
})();
