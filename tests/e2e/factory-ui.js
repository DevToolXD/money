// 화면: 공장 카드. 시작 전에 시간·재료값·판매액·이익이 보이고, 돌리면 "돌아가는 중" 표시와 만든 개수·남은 시간·끝나는 시각이 보이고,
// 한 개씩 나올 때마다 재고가 바로 늘어요
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const emu = fs.readFileSync(path.join(__dirname, '..', 'out', 'firebase.emu.js'), 'utf8');
const res = []; const ok = (n, v) => { res.push(!!v); console.log((v ? 'PASS ' : 'FAIL ') + n); };
const DB = 'http://127.0.0.1:8081/v1/projects/money-sim-36ed8/databases/(default)/documents';
const H = { 'content-type': 'application/json', authorization: 'Bearer owner' };
const raw = async (p) => (await (await fetch(`${DB}/${p}`, { headers: H })).json());
const num = (f) => Number(f.integerValue ?? f.doubleValue ?? 0);
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-web-security'] });
  const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.route('**/app/firebase.js*', (r) => r.fulfill({ contentType: 'text/javascript', body: emu }));
  await p.route('**/index.html*', async (r) => { const resp = await r.fetch(); const t = (await resp.text()).replace("connect-src 'self'", "connect-src 'self' http://127.0.0.1:*"); r.fulfill({ response: resp, body: t }); });
  await p.goto('http://127.0.0.1:8765/index.html'); await p.waitForTimeout(3500);
  await p.evaluate((u) => window.cloud.signUp(u, 'abc123', '공장장'), 'fu' + Date.now().toString(36).slice(-4));
  await p.reload(); await p.waitForTimeout(6000);
  const uid = await p.evaluate(() => window.cloud.uid);
  await fetch(`${DB}/wallets/${uid}?updateMask.fieldPaths=bal`, { method: 'PATCH', headers: H, body: JSON.stringify({ fields: { bal: { integerValue: '1000' } } }) });
  await p.waitForTimeout(2500);
  const cid = await p.evaluate(() => window.cloud.foundCompany('공장 화면', '', 'food')); await p.waitForTimeout(2500);
  await p.evaluate((c) => window.cloud.labCash(c, 100, 1), cid); await p.waitForTimeout(2500);
  const pid = await p.evaluate((c) => window.cloud.createProduct(c, { cat: 'food', group: 'water', item: 'water', name: '화면 생수', shape: 1, cap: 3, capColor: 5, color: -1, costCents: 100, priceCents: 300, paused: false, active: true }), cid);
  await p.reload(); await p.waitForTimeout(5000);
  await p.evaluate(() => window.tabbar.flipPage()); await p.waitForTimeout(500);
  await p.evaluate(() => document.querySelector('.tabbar .tab[data-tab="business"]').click()); await p.waitForTimeout(3000);
  const est = (await p.textContent('#fac-est')).replace(/\s+/g, ' ');
  console.log('EST:', est);
  ok('시작 전: 50개 걸리는 시간 (약 50분)', est.includes('50분'));
  ok('시작 전: 재료값 합계 50 토큰', est.includes('재료값 합계') && est.includes('50 토큰'));
  ok('시작 전: 다 팔면 150 토큰', est.includes('150 토큰'));
  ok('시작 전: 예상 이익 100 토큰', est.includes('예상 이익') && est.includes('100 토큰'));
  ok('시작 전: 금고 100 토큰', est.includes('회사 금고') && est.includes('100 토큰'));
  await p.fill('#fac-n', '500'); await p.waitForTimeout(300);
  ok('금고보다 많이 정하면 모자라다고 알려 줘요', (await p.textContent('#fac-est')).includes('재료값이 모자라요') && (await p.textContent('#fac-est')).includes('100개까지만'));
  await p.fill('#fac-n', '5'); await p.waitForTimeout(300);
  await p.evaluate(() => document.getElementById('fac-start').scrollIntoView({ block: 'center' })); await p.waitForTimeout(300);
  await p.click('#fac-start'); await p.waitForTimeout(3500);
  const btn = (await p.textContent('#fac-start')).replace(/\s+/g, ' ');
  ok('돌리면 버튼이 "공장 돌아가는 중 · 0 / 5개"', btn.includes('공장 돌아가는 중') && btn.includes('0 / 5개'));
  ok('버튼은 눌리지 않아요', await p.isDisabled('#fac-start'));
  const live = (await p.textContent('#fac-left')).replace(/\s+/g, ' ');
  console.log('LIVE:', live);
  ok('몇 개 만들었는지', live.includes('0 / 5개 만들었어요'));
  ok('남은 개수와 다음 1개까지', live.includes('남은 5개') && live.includes('다음 1개까지'));
  ok('다 만들어지기까지와 끝나는 시각', live.includes('다 만들어지기까지') && /(오전|오후) \d+:\d\d에 끝나요/.test(live));
  // 2분 5초 전에 시작한 것으로 바꿔요 → 두 개가 나와 있어야 해요
  await fetch(`${DB}/companies/${cid}/lab/main?updateMask.fieldPaths=prod`, { method: 'PATCH', headers: H, body: JSON.stringify({ fields: { prod: { mapValue: { fields: { pid: { stringValue: pid }, left: { integerValue: '5' }, total: { integerValue: '5' }, at: { timestampValue: new Date(Date.now() - 125000).toISOString() } } } } } }) });
  await p.reload(); await p.waitForTimeout(5500);
  await p.evaluate(() => window.tabbar.flipPage()); await p.waitForTimeout(500);
  await p.evaluate(() => document.querySelector('.tabbar .tab[data-tab="business"]').click()); await p.waitForTimeout(3500);
  const live2 = (await p.textContent('#fac-left')).replace(/\s+/g, ' ');
  console.log('LIVE2:', live2);
  ok('두 개가 나와서 "2 / 5개"', live2.includes('2 / 5개 만들었어요') || live2.includes('3 / 5개 만들었어요'));
  await p.waitForTimeout(5000);
  const stockServer = (await raw(`companies/${cid}/products/${pid}`)).fields.stock;
  ok('나온 만큼 서버 재고에 바로 들어가요 (정산)', stockServer && num(stockServer) >= 2);
  const cash = num((await raw(`companies/${cid}/lab/main`)).fields.cash);
  ok('재료값은 만든 만큼 금고에서 나가요', cash <= 10000 - 200 && cash >= 10000 - 400);
  ok('화면 재고 숫자도 같아요', Number((await p.textContent('#wk-stock')).replace(/\D/g, '')) >= 2);
  await p.evaluate(() => document.getElementById('biz-factory').scrollIntoView({ block: 'start' })); await p.waitForTimeout(400);
  await p.screenshot({ path: path.join(__dirname, 'shots', 'factory-ui.png') });
  ok('화면 오류 없음', errs.length === 0); if (errs.length) console.log(errs.slice(0, 3));
  console.log(`\n${res.filter(Boolean).length}/${res.length} 통과`);
  await b.close(); process.exit(res.every(Boolean) ? 0 : 1);
})();
