// 진짜 번들 + 진짜 규칙 (에뮬레이터): 오너가 인증토큰을 자동으로 받아 토큰을 주고, 공지를 올리고, 계정 데이터를 지워요. 다른 사람은 못 해요
const { chromium } = require('playwright');
const fs = require('fs');
const emu = fs.readFileSync(require('path').join(__dirname, '..', 'out', 'firebase.emu.js'), 'utf8');
const res = [];
const ok = (n, v) => { res.push(!!v); console.log((v ? 'PASS ' : 'FAIL ') + n); };
const DB = 'http://127.0.0.1:8081/v1/projects/money-sim-36ed8/databases/(default)/documents';
const open = async (b) => {
  const page = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
  await page.route('**/app/firebase.js*', (r) => r.fulfill({ contentType: 'text/javascript', body: emu }));
  await page.route('**/index.html*', async (r) => { const resp = await r.fetch(); const t = (await resp.text()).replace("connect-src 'self'", "connect-src 'self' http://127.0.0.1:*"); r.fulfill({ response: resp, body: t }); });
  await page.goto('http://127.0.0.1:8765/index.html'); await page.waitForTimeout(3500);
  return page;
};
const patch = (path, fields, mask) => fetch(`${DB}/${path}?${mask.map((m) => 'updateMask.fieldPaths=' + m).join('&')}`, { method: 'PATCH', headers: { 'content-type': 'application/json', authorization: 'Bearer owner' }, body: JSON.stringify({ fields }) });
const rawDoc = async (path) => (await (await fetch(`${DB}/${path}`, { headers: { authorization: 'Bearer owner' } })).json());
const wallet = async (uid) => { const d = await rawDoc(`wallets/${uid}`); return d.fields ? Number(d.fields.bal.integerValue) : null; };
const call = (p, fn, args) => p.evaluate(([f, a]) => window.cloud[f](...a).then((r) => (r === undefined ? 'ok' : r), (e) => 'ERR ' + (e.code || e.message)), [fn, args]);
const wait = (p, ms) => p.waitForTimeout(ms);
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--disable-web-security'] });
  const pOwner = await open(b), pT = await open(b);
  await pOwner.evaluate(() => window.cloud.signUp('owner', 'abc123', '관리자'));
  await pOwner.reload(); await wait(pOwner, 6000);
  const uOwner = await pOwner.evaluate(() => window.cloud.uid);
  await pT.evaluate(() => window.cloud.signUp('tgtperson1', 'abc123', '대상사람'));
  await pT.reload(); await wait(pT, 6000);
  const uT = await pT.evaluate(() => window.cloud.uid);
  await wait(pOwner, 2300);
  ok('오너 계정은 owner 아이디로 만들어졌어요', (await rawDoc(`profiles/${uOwner}`)).fields.id.stringValue === 'owner');
  await wait(pT, 2300);
  ok('일반 사람은 토큰을 지급할 수 없어요', (await call(pT, 'adminGrant', ['owner', 5])).startsWith('ERR'));
  ok('일반 사람은 공지를 올릴 수 없어요', (await call(pT, 'adminNotice', ['나쁜 공지'])).startsWith('ERR'));
  const before = (await wallet(uT)) ?? 0;
  ok('오너: 대상에게 토큰 지급', (await call(pOwner, 'adminGrant', ['tgtperson1', 50])) === uT);
  await wait(pOwner, 2300);
  ok('지갑이 50 늘었어요', (await wallet(uT)) === before + 50);
  ok('지급 뒤 인증토큰은 없어졌어요', (await fetch(`${DB}/adminAuth/${uOwner}`, { headers: { authorization: 'Bearer owner' } }).then((r) => r.json())).error !== undefined);
  ok('오너: 공지 올리기', typeof (await call(pOwner, 'adminNotice', [{ title: '점검', body: '점검 안내 테스트' }])) === 'string');
  await wait(pT, 500);
  const notices = await call(pT, 'noticeList', [await call(pT, 'noticeIds', [])]);
  ok('모두 공지를 읽어요', Array.isArray(notices) && notices.some((n) => n.body === '점검 안내 테스트'));
  ok('없는 아이디는 지급 못 해요', (await call(pOwner, 'adminGrant', ['nobodyhere9', 5])).startsWith('ERR'));
  await wait(pOwner, 2300);
  ok('오너: 대상 계정 데이터 지우기', (await call(pOwner, 'adminDelete', ['tgtperson1'])) === uT);
  const prof = await fetch(`${DB}/profiles/${uT}`, { headers: { authorization: 'Bearer owner' } }).then((r) => r.json());
  ok('프로필과 지갑이 지워졌어요', prof.error !== undefined && (await wallet(uT)) === null);
  const logs = await fetch(`${DB}/adminLog`, { headers: { authorization: 'Bearer owner' } }).then((r) => r.json());
  ok('관리 기록이 남았어요', Array.isArray(logs.documents) && logs.documents.length >= 1);
  console.log(`\n${res.filter(Boolean).length}/${res.length} 통과`);
  await b.close();
  process.exit(res.every(Boolean) ? 0 : 1);
})();
