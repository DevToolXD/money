// 화면: 홈 지도에서 땅을 사고, 이름을 짓고, 건물을 올리고, 다른 사람이 들어오면 통행료를 내고, 주인이 받고, 팔아요
const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const emu = fs.readFileSync(path.join(__dirname, '..', 'out', 'firebase.emu.js'), 'utf8');
const res = []; const ok = (n, v) => { res.push(!!v); console.log((v ? 'PASS ' : 'FAIL ') + n); };
const DB = 'http://127.0.0.1:8081/v1/projects/money-sim-36ed8/databases/(default)/documents';
const H = { 'content-type': 'application/json', authorization: 'Bearer owner' };
const raw = async (p) => (await (await fetch(`${DB}/${p}`, { headers: H })).json());
const num = (f) => Number(f?.integerValue ?? f?.doubleValue ?? 0);
const setBal = (uid, v) => fetch(`${DB}/wallets/${uid}?updateMask.fieldPaths=bal`, { method: 'PATCH', headers: H, body: JSON.stringify({ fields: { bal: { integerValue: String(v) } } }) });
const TILE = '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#f2efe9" stroke="#dcd6c8"/></svg>';
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-web-security'] });
  const mk = async (name, id) => {
    const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, geolocation: { latitude: 37.5446, longitude: 127.0557, accuracy: 10 }, permissions: ['geolocation'] });
    const p = await ctx.newPage(); p.errs = []; p.on('pageerror', (e) => p.errs.push(e.message));
    await p.route('**/app/firebase.js*', (r) => r.fulfill({ contentType: 'text/javascript', body: emu }));
    await p.route('**/index.html*', async (r) => { const resp = await r.fetch(); const t = (await resp.text()).replace("connect-src 'self'", "connect-src 'self' http://127.0.0.1:*"); r.fulfill({ response: resp, body: t }); });
    await p.route('https://tile.openstreetmap.org/**', (r) => r.fulfill({ contentType: 'image/svg+xml', body: TILE }));
    await p.goto('http://127.0.0.1:8765/index.html'); await p.waitForTimeout(3500);
    await p.evaluate(([u, n]) => window.cloud.signUp(u, 'abc123', n), [id, name]);
    await p.reload(); await p.waitForTimeout(6000);
    p.uid = await p.evaluate(() => window.cloud.uid);
    return p;
  };
  const home = async (p) => { await p.evaluate(() => document.querySelector('.tabbar .tab[data-tab="home"]').click()); await p.waitForTimeout(3500); };
  const toast = async (p, t) => { for (let i = 0; i < 40; i++) { if (((await p.textContent('.toast').catch(() => '')) || '').includes(t)) return true; await p.waitForTimeout(250); } return false; };
  const t = Date.now().toString(36).slice(-4);
  const A = await mk('땅주인', 'la' + t);
  await setBal(A.uid, 500); await A.waitForTimeout(2500);
  await home(A);
  ok('지도와 내 토큰이 보여요', await A.isVisible('#map-view') && (await A.textContent('#map-hud')).includes('500'));
  // 내 위치(화면 가운데)의 칸을 눌러요
  await A.mouse.click(195, 422); await A.waitForTimeout(700);
  ok('빈 땅 카드: 사기 버튼', (await A.textContent('#land-sheet')).includes('주인 없는 땅') && await A.isVisible('#land-sheet [data-act="buy"]'));
  await A.click('#land-sheet [data-act="buy"]');
  ok('땅을 샀어요', await toast(A, '땅을 샀어요'));
  await A.waitForTimeout(2500);
  const lands = (await raw('lands')).documents || [];
  ok('서버에 내 땅 하나', lands.length === 1 && lands[0].fields.owner.stringValue === A.uid);
  const lid = lands[0].name.split('/').pop();
  ok('지갑에서 10 토큰이 빠졌어요', num((await raw(`wallets/${A.uid}`)).fields.bal) === 490);
  ok('내 땅 카드: 이름 칸·짓기', await A.isVisible('#ld-name') && (await A.textContent('#land-sheet')).includes('집 1채 짓기'));
  await A.fill('#ld-name', '성수 1번지'); await A.click('#land-sheet [data-act="name"]');
  ok('이름을 지었어요', await toast(A, '땅 이름을 바꿨어요'));
  await A.waitForTimeout(1500);
  await A.click('#land-sheet [data-act="build"]');
  ok('집을 지었어요', await toast(A, '집 1채을(를) 지었어요'));
  await A.waitForTimeout(2500);
  let L = (await raw(`lands/${lid}`)).fields;
  ok('서버: 이름과 1단계', L.name.stringValue === '성수 1번지' && num(L.lv) === 1 && num((await raw(`wallets/${A.uid}`)).fields.bal) === 470);
  await A.screenshot({ path: path.join(__dirname, 'shots', 'land-mine.png') });
  // 다른 사람이 같은 자리에 들어와요
  const B = await mk('지나가는이', 'lb' + t);
  await setBal(B.uid, 100); await B.waitForTimeout(2500);
  await home(B);
  ok('남의 땅에 들어가면 통행료 2 토큰', await toast(B, '통행료 2 토큰을 냈어요'));
  await B.waitForTimeout(2500);
  ok('서버: 내 지갑 98, 땅에 2 모임', num((await raw(`wallets/${B.uid}`)).fields.bal) === 98 && num((await raw(`lands/${lid}`)).fields.pot) === 2);
  await B.mouse.click(195, 422); await B.waitForTimeout(1500);
  const bs = await B.textContent('#land-sheet');
  ok('남의 땅 카드: 주인·이름·통행료, 살 수 없어요', bs.includes('땅주인님의 땅') && bs.includes('성수 1번지') && !(await B.$('#land-sheet [data-act="buy"]')));
  await B.screenshot({ path: path.join(__dirname, 'shots', 'land-other.png') });
  await B.reload(); await B.waitForTimeout(6000); await home(B); await B.waitForTimeout(2500);
  ok('같은 땅은 1시간 안에 다시 내지 않아요', num((await raw(`wallets/${B.uid}`)).fields.bal) === 98);
  // 주인이 받아요
  await A.reload(); await A.waitForTimeout(6000); await home(A);
  await A.mouse.click(195, 422); await A.waitForTimeout(1500);
  ok('모인 통행료가 보여요', (await A.textContent('#land-sheet')).includes('통행료 받기 · 2 토큰'));
  await A.click('#land-sheet [data-act="rent"]');
  ok('통행료를 받았어요', await toast(A, '통행료 2 토큰을 받았어요'));
  await A.waitForTimeout(2500);
  ok('서버: 지갑 472, 땅은 0', num((await raw(`wallets/${A.uid}`)).fields.bal) === 472 && num((await raw(`lands/${lid}`)).fields.pot) === 0);
  await A.click('#land-sheet [data-act="sell"]'); await A.waitForTimeout(600);
  await A.click('#alert-ok');
  ok('땅을 팔았어요 (15 토큰)', await toast(A, '땅을 팔고 15 토큰을 받았어요'));
  await A.waitForTimeout(2500);
  ok('서버: 땅이 없어지고 지갑 487', !((await raw('lands')).documents || []).length && num((await raw(`wallets/${A.uid}`)).fields.bal) === 487);
  const errs = [...A.errs, ...B.errs];
  ok('화면 오류 없음', errs.length === 0); if (errs.length) console.log(errs.slice(0, 3));
  console.log(`\n${res.filter(Boolean).length}/${res.length} 통과`);
  await b.close(); process.exit(res.every(Boolean) ? 0 : 1);
})();
